CREATE TABLE region (
    code VARCHAR(16) PRIMARY KEY,
    name VARCHAR(200) NOT NULL
);
CREATE TABLE fuel_type (
    code VARCHAR(32) PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);
INSERT INTO fuel_type (code, name) VALUES ('DIESEL', 'Дизельное топливо'), ('AI92', 'АИ-92');
CREATE TABLE data_source (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    data_mode VARCHAR(16) NOT NULL CHECK (data_mode IN ('OPEN_DATA', 'DEMO', 'BENZUP')),
    methodology VARCHAR(2000) NOT NULL,
    last_imported_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE regional_price (
    source_id VARCHAR(64) NOT NULL REFERENCES data_source(id),
    region_code VARCHAR(16) NOT NULL REFERENCES region(code),
    fuel_code VARCHAR(32) NOT NULL REFERENCES fuel_type(code),
    observed_on DATE NOT NULL,
    frequency VARCHAR(16) NOT NULL CHECK (frequency IN ('DAILY', 'WEEKLY', 'MONTHLY')),
    price NUMERIC(18, 6) NOT NULL CHECK (price > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'RUB'),
    unit VARCHAR(16) NOT NULL CHECK (unit = 'LITER'),
    source_url VARCHAR(2000) NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source_id, region_code, fuel_code, observed_on)
);
CREATE INDEX regional_price_history ON regional_price (source_id, region_code, fuel_code, observed_on);
CREATE TABLE import_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id VARCHAR(64) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED')),
    row_count INTEGER NOT NULL CHECK (row_count >= 0),
    rejected_count INTEGER NOT NULL CHECK (rejected_count >= 0),
    error_code VARCHAR(64)
);

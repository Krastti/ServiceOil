CREATE TABLE vehicle_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    tank_capacity NUMERIC(12, 2) NOT NULL CHECK (tank_capacity > 0 AND tank_capacity <= 1000000),
    fuel_code VARCHAR(32) NOT NULL CHECK (fuel_code IN ('DIESEL', 'AI92'))
);
